export function getDashboardNavigation(user, isSuperAdmin) {
  const permissionSet = new Set(user?.permissions || []);
  return dashboardNavigation.filter((item) =>
    isSuperAdmin
      ? item.superAdminOnly
      : !item.superAdminOnly &&
        (item.permission
          ? permissionSet.has(item.permission)
          : !item.roles || item.roles.includes(user?.role)),
  );
}
